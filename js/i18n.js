window.JB_I18n = {
	detectDefaultLang() {
		const saved = localStorage.getItem(window.JB_I18N.STORAGE_KEY);
		if (saved && window.JB_I18N.SUPPORTED.includes(saved)) return saved;
		const nav = (navigator.language || "en").toLowerCase();
		return nav.startsWith("es") ? "es" : "en";
	},

	setPressed(lang) {
		const pairs = [
			["lang-es", "es"],
			["lang-en", "en"],
		];
		for (const [id, l] of pairs) {
			const el = document.getElementById(id);
			if (!el) continue;
			const active = l === lang;
			el.setAttribute("aria-pressed", String(active));
			el.classList.toggle("lang-active", active);
		}
	},

	apply(lang) {
		const table = window.JB_I18N.dict[lang] || window.JB_I18N.dict.en;
		document.documentElement.lang = lang;
		for (const el of document.querySelectorAll("[data-i18n]")) {
			const key = el.getAttribute("data-i18n");
			if (!key) continue;
			const value = table[key];
			if (typeof value === "string") el.textContent = value;
		}
		for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
			const key = el.getAttribute("data-i18n-placeholder");
			if (!key) continue;
			const value = table[key];
			if (typeof value === "string") el.setAttribute("placeholder", value);
		}
		for (const el of document.querySelectorAll("[data-i18n-aria-label]")) {
			const key = el.getAttribute("data-i18n-aria-label");
			if (!key) continue;
			const value = table[key];
			if (typeof value === "string") el.setAttribute("aria-label", value);
		}
		this.setPressed(lang);
		document.dispatchEvent(new CustomEvent("jb:lang", { detail: { lang } }));
	},

	setLang(lang) {
		localStorage.setItem(window.JB_I18N.STORAGE_KEY, lang);
		this.apply(lang);
	},

	getLang() {
		return localStorage.getItem(window.JB_I18N.STORAGE_KEY) || this.detectDefaultLang();
	},

	t(key, lang) {
		const table = window.JB_I18N.dict[lang || this.getLang()] || window.JB_I18N.dict.en;
		return table[key] || key;
	},
};
